    Inter,
    ui-sans-serif,
    system-ui,
    -apple-system,
    BlinkMacSystemFont,
    "Segoe UI",
    sans-serif;
  background: #020617;
  color: #f8fafc;
}
EOF

  replace_file_if_different "${WEB_DIR}/src/components/layout/app-shell.tsx" <<'EOF'
import type { JSX } from "solid-js";

export function AppShell(props: { children: JSX.Element }) {
  return (
    <div class="min-h-screen bg-slate-950 text-slate-100">
      {props.children}
    </div>
  );
}
EOF

  replace_file_if_different "${WEB_DIR}/src/lib/query/client.ts" <<'EOF'
import { QueryClient } from "@tanstack/solid-query";

export function createAppQueryClient() {
  return new QueryClient();
}
EOF

  replace_file_if_different "${WEB_DIR}/src/lib/seo/defaults.ts" <<'EOF'
export const DEFAULT_SEO = {
  title: "Monorepo Web",
  description: "TanStack Start + Solid web application"
};
EOF

  append_if_missing "${WEB_DIR}/public/.gitkeep" ""

  patch_root_tsconfig
  patch_root_readme

  echo "Scaffolded apps/web as TanStack Start + Solid."
  echo
  echo "Next steps:"
  echo "  1. bun install"
  echo "  2. bun run --filter @repo/web dev"
  echo "  3. then apply the Tailwind/Kobalte overlay"
}

main "$@"